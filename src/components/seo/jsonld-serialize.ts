// Сериализация данных Schema.org в строку для <script type="application/ld+json">.
//
// Живёт отдельным .ts, а не внутри JsonLd.tsx, по причине раннера: node:test
// гоняет файлы нативным стриппингом типов Node, а JSX он не трансформирует —
// импорт .tsx падает с ERR_UNKNOWN_FILE_EXTENSION. Логика, оставленная в
// компоненте, тестом недостижима в принципе, поэтому она здесь.

/**
 * JSON для вставки внутрь тега скрипта. Отличается от JSON.stringify ровно одним:
 * «меньше» уходит юникодным эскейпом <.
 *
 * Зачем: содержимое <script> браузер читает не как JSON, а как текст до первого
 * «</script» — и закрывает тег там. Названия и описания товаров приходят из
 * админки, в том числе загрузкой прайса, то есть из файла, который принёс кто-то
 * извне; JSON.stringify последовательность «</script>» не трогает и отдаёт её в
 * разметку как есть. Тег закроется изнутри, разметка станет невалидной, а хвост
 * строки уедет в HTML уже как разметка.
 *
 * Хватает одного «меньше»: без него нельзя ни закрыть тег, ни открыть комментарий
 * «<!--», который в script тоже меняет разбор. < — обычный эскейп JSON, его
 * понимает любой парсер, поэтому РАЗОБРАННЫЕ данные не меняются: угловые скобки
 * остаются на своих местах в значении, меняется только запись в строке.
 */
export function serializeJsonLd(data: Record<string, unknown>): string {
  // Вне строковых литералов «меньше» в JSON не встречается, так что замена
  // по всей строке затрагивает только содержимое значений.
  return JSON.stringify(data).replace(/</g, "\\u003c");
}
